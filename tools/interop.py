"""Bidirectional compatibility checks against the official Python MCAP package."""
import io
import os
from pathlib import Path
import subprocess
import sys
sys.stdout.reconfigure(encoding="utf-8")
sys.stderr.reconfigure(encoding="utf-8")

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "_interop_deps"))
from mcap.reader import make_reader
from mcap.writer import Writer, CompressionType

moon = os.environ.get("MOON", "moon")
output = subprocess.run(
    [moon, "run", "cmd/main", "--target", "js"], cwd=ROOT,
    capture_output=True, text=True, encoding="utf-8", check=True,
)
line = next(x for x in output.stdout.splitlines() if x.startswith("MCAP_HEX="))
data = bytes.fromhex(line.removeprefix("MCAP_HEX="))
reader = make_reader(io.BytesIO(data), validate_crcs=True)
messages = list(reader.iter_messages())
assert len(messages) == 6
assert all(channel.topic == "/events" for _, channel, _ in messages)
assert [message.log_time for _, _, message in messages] == [i * 10**9 for i in range(1, 7)]
assert all(message.data == b'{"value":1}' for _, _, message in messages)
attachments = list(reader.iter_attachments())
assert len(attachments) == 1 and attachments[0].data == b"{}"
print("MoonBit -> official Python reader: messages, chunks, indexes, CRCs and attachment passed")

tests = []
for chunked in (False, True):
    stream = io.BytesIO()
    writer = Writer(stream, compression=CompressionType.NONE, use_chunking=chunked,
                    enable_crcs=True, enable_data_crcs=True, chunk_size=100)
    writer.start(library="official-python-fixture/1.3.0")
    schema = writer.register_schema("Event", "jsonschema", b"{}")
    channel = writer.register_channel("/reference", "json", schema, {"source": "python"})
    for i in range(4):
        writer.add_message(channel, i + 10, b'{"i":1}', i + 10, sequence=i)
    writer.add_attachment(1, 2, "calibration", "application/json", b"{}")
    writer.add_metadata("run", {"id": "reference"})
    writer.finish()
    fixture = stream.getvalue().hex()
    tests.append(f'''///|
test "official Python {'chunked' if chunked else 'sequential'} fixture" {{
  try {{
  let bytes = @moonmcap.decode_hex("{fixture}")
  let log = @moonmcap.read_log(bytes)
  assert_eq(log.messages.length(), 4)
  assert_eq(log.messages[3].sequence, 3U)
  assert_eq(log.channels[0].topic, "/reference")
  assert_eq(log.attachments[0].data, b"{{}}")
  assert_eq(log.metadata[0].entries, [("id", "reference")])
  ignore(@moonmcap.validate_file_indexes(bytes))
  ignore(@moonmcap.validate_summary(bytes))
  assert_eq(@moonmcap.validate_attachment_indexes(bytes), 1)
  assert_eq(@moonmcap.validate_metadata_indexes(bytes), 1)
  }} catch {{ @moonmcap.Invalid(reason) => fail(reason); _ => fail("unexpected assertion failure") }}
}}
''')
(ROOT / "reference_fixture_test.mbt").write_text(
    "// Generated by tools/interop.py from official mcap==1.3.0. Not implementation LOC.\n" + "\n".join(tests),
    encoding="utf-8",
)
result = subprocess.run([moon, "test"], cwd=ROOT, capture_output=True, text=True, encoding="utf-8")
if result.returncode:
    print(result.stdout)
    print(result.stderr)
    raise SystemExit(result.returncode)
print(result.stdout.strip().splitlines()[-1])
print("Official Python -> MoonBit reader: sequential and indexed chunked fixtures passed")

