def vectors():
    descriptors={}
    def include(desc):
        for dep in desc.dependencies:include(dep)
        descriptors[desc.name]=pb.FileDescriptorProto.FromString(desc.serialized_pb)
    samples=[]
    for seconds,nanos in [(0,0),(-1,1),(-62135596800,0),(253402300799,999999999),(1700000000,123000000),(1700000000,123456000)]:samples.append(timestamp_pb2.Timestamp(seconds=seconds,nanos=nanos))
    for seconds,nanos in [(0,-1),(-3,-123000000),(315576000000,999999999),(0,0)]:samples.append(duration_pb2.Duration(seconds=seconds,nanos=nanos))
    for cls,value in [(wrappers_pb2.Int64Value,-9223372036854775808),(wrappers_pb2.UInt64Value,18446744073709551615),(wrappers_pb2.BytesValue,b'\x00\xff'),(wrappers_pb2.BoolValue,False),(wrappers_pb2.StringValue,''),(wrappers_pb2.DoubleValue,float('inf')),(wrappers_pb2.FloatValue,1.25),(wrappers_pb2.Int32Value,-7),(wrappers_pb2.UInt32Value,7)]:samples.append(cls(value=value))
    samples+=[struct_pb2.Value(null_value=0),struct_pb2.Value(number_value=1.25),struct_pb2.Value(bool_value=False),struct_pb2.Value(string_value=''),empty_pb2.Empty(),field_mask_pb2.FieldMask(paths=['foo_bar.x','hello_world'])]
    struct=struct_pb2.Struct();struct.update({'x':None,'n':2.5,'array':[True,{'text':'moon'}]});samples+=[struct,struct_pb2.ListValue(values=[struct_pb2.Value(string_value='x')])]
    for message in [samples[0],samples[10],struct,empty_pb2.Empty()]:
        value=any_pb2.Any();value.Pack(message);samples.append(value)
    samples.append(any_pb2.Any())
    for message in samples:include(message.DESCRIPTOR.file)
    f=pb.FileDescriptorProto(name='presence.proto',package='test',syntax='proto3')
    m=f.message_type.add(name='Presence');m.oneof_decl.add(name='choice');m.oneof_decl.add(name='_optional_n')
    m.field.add(name='n',number=1,type=5,label=1)
    m.field.add(name='items',number=2,type=5,label=3)
    m.field.add(name='chosen',number=3,type=5,label=1,oneof_index=0)
    m.field.add(name='optional_n',number=4,type=5,label=1,oneof_index=1,proto3_optional=True)
    descriptors[f.name]=f
    pool=descriptor_pool.DescriptorPool();pool.Add(f);cls=message_factory.GetMessageClass(pool.FindMessageTypeByName('test.Presence'))
    samples += [cls(),cls(chosen=0,optional_n=0),cls(n=0,items=[0])]
    p2=pb.FileDescriptorProto(name='defaults.proto',package='test',syntax='proto2');msg=p2.message_type.add(name='Defaults');msg.field.add(name='n',number=1,type=5,label=1,default_value='42');msg.field.add(name='items',number=2,type=5,label=3)
    descriptors[p2.name]=p2;pool.Add(p2);p2cls=message_factory.GetMessageClass(pool.FindMessageTypeByName('test.Defaults'));samples += [p2cls(),p2cls(n=42)]
    # Also test a non-special Any: inline object fields rather than a value wrapper.
    packed=any_pb2.Any();packed.Pack(cls(n=7));samples.append(packed)
    default_pool=descriptor_pool.Default();default_pool.Add(f)
    # A missing map message value is an empty message instance, including its WKT mapping.
    fm=pb.FileDescriptorProto(name='mapped_time.proto',package='test',syntax='proto3',dependency=['google/protobuf/timestamp.proto'])
    mm=fm.message_type.add(name='MappedTime');entry=mm.nested_type.add(name='TimesEntry');entry.options.map_entry=True
    entry.field.add(name='key',number=1,type=9,label=1);entry.field.add(name='value',number=2,type=11,label=1,type_name='.google.protobuf.Timestamp')
    mm.field.add(name='times',number=1,type=11,label=3,type_name='.test.MappedTime.TimesEntry')
    default_pool.Add(fm);descriptors[fm.name]=fm
    mapped=message_factory.GetMessageClass(default_pool.FindMessageTypeByName('test.MappedTime'))();mapped.ParseFromString(b'\x0a\x05\x0a\x03key');samples.append(mapped)
    result=[]
    for i,message in enumerate(samples):
        for defaults in (False,True):
            expected=json_format.MessageToDict(message,always_print_fields_with_no_presence=defaults)
            result.append({'type':message.DESCRIPTOR.full_name,'wire':message.SerializeToString().hex(),'defaults':defaults,'expected':expected})
    result.append({'type':'test.Presence','wire':'08001200','defaults':False,'expected':{}})
    return pb.FileDescriptorSet(file=list(descriptors.values())).SerializeToString(),result


def main():
    work=ROOT/'_interop/protojson';work.mkdir(parents=True,exist_ok=True)
    descriptor,cases=vectors();(work/'schema.bin').write_bytes(descriptor)
    if '--generate' in sys.argv:
        text='// Generated by tools/protojson_workflows.py with Google protobuf 6.33.0.\n///|\n'
        text+='test "ProtoJSON well known mappings presence and defaults match official serializers" {\n'
        text+='  let descriptor = @moonmcap.decode_hex("'+descriptor.hex()+'")\n'
        for case in cases:
            options='@moonmcap.protobuf_json_options()' if not case['defaults'] else '{ ..@moonmcap.protobuf_json_options(), emit_defaults: true }'
            expected=json.dumps(json.dumps(case['expected'],ensure_ascii=True),ensure_ascii=True)
            text+=f'  assert_eq(@moonmcap.protobuf_decoder(descriptor, options={options}).decode("{case["type"]}", @moonmcap.decode_hex("{case["wire"]}")), @json.parse({expected}))\n'
        text+='}\n';(ROOT/'protojson_fixture_test.mbt').write_text(text,encoding='utf-8');print('Generated',len(cases),'portable official mapping cases');return
    subprocess.run([os.environ.get('MOON','moon'),'build','--target','js'],cwd=ROOT,capture_output=True,check=True)
    cli=ROOT/'_build/js/debug/build/cmd/decode/decode.js'
    def run(name,wire,defaults=False):
        (work/'message.bin').write_bytes(wire)
        return subprocess.run([os.environ.get('NODE','node'),str(cli),'raw',str(work/'schema.bin'),str(work/'message.bin'),name,'--protojson',*(['--emit-defaults'] if defaults else [])],cwd=ROOT,capture_output=True,text=True,encoding='utf-8',timeout=20)
    for case in cases:
        result=run(case['type'],bytes.fromhex(case['wire']),case['defaults'])
        assert result.returncode==0,(case,result.stderr)
        assert json.loads(result.stdout)==case['expected'],(case,result.stdout)
    invalid=[timestamp_pb2.Timestamp(seconds=253402300800),timestamp_pb2.Timestamp(nanos=-1),duration_pb2.Duration(seconds=1,nanos=-1),field_mask_pb2.FieldMask(paths=['bad__name']),struct_pb2.Value(),struct_pb2.Value(number_value=float('nan')),any_pb2.Any(type_url='type/unknown.Type',value=b''),struct_pb2.Struct.FromString(b'\x0a\x03\x0a\x01x')]
    for message in invalid:
        result=run(message.DESCRIPTOR.full_name,message.SerializeToString());assert result.returncode==2,(message,result.stdout)
    invalid_descriptors=[]
    for mode in ('reserved','oneof','required','optional','shared-optional','duplicate-name','package'):
        file=pb.FileDescriptorProto(name='invalid.proto',package='test',syntax='proto3');message=file.message_type.add(name='Invalid');field=message.field.add(name='n',number=1,type=5,label=1)
        if mode=='reserved':field.number=19001
        if mode=='oneof':field.oneof_index=0
        if mode=='required':field.label=2
        if mode=='optional':field.proto3_optional=True
        if mode=='shared-optional':
            message.oneof_decl.add(name='_n');field.proto3_optional=True;field.oneof_index=0;message.field.add(name='other',number=2,type=5,label=1,oneof_index=0)
        if mode=='duplicate-name':message.field.add(name='n',json_name='other',number=2,type=5,label=1)
        if mode=='package':file.package='bad..package'
        (work/'schema.bin').write_bytes(pb.FileDescriptorSet(file=[file]).SerializeToString())
        result=run('test.Invalid',b'');assert result.returncode==2,(mode,result.stdout)
        invalid_descriptors.append(mode)
    report={'result':'passed','reference':'Google protobuf 6.33.0','canonical_cases':len(cases),'invalid_cases':len(invalid),'invalid_descriptors':invalid_descriptors,'legacy_mode':'verified by existing protobuf_workflows and portable fixtures'}
    (work/'report.json').write_text(json.dumps(report,indent=2)+'\n');print('ProtoJSON workflows passed:',len(cases),'official cases and',len(invalid),'invalid cases')


if __name__=='__main__':main()
