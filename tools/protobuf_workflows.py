from google.protobuf import descriptor_pb2 as pb, descriptor_pool, message_factory, json_format
from mcap.writer import Writer, CompressionType


def schema():
    file = pb.FileDescriptorProto(name='telemetry.proto', package='telemetry', syntax='proto3')
    msg = file.message_type.add(name='Sample')
    enum = msg.enum_type.add(name='State')
    enum.value.add(name='IDLE', number=0); enum.value.add(name='RUN', number=1)
    child = msg.nested_type.add(name='Child')
    child.field.add(name='a', json_name='a', number=1, type=5, label=1)
    child.field.add(name='b', json_name='b', number=2, type=9, label=1)
    pair = msg.nested_type.add(name='LabelsEntry'); pair.options.map_entry = True
    pair.field.add(name='key', json_name='key', number=1, type=9, label=1)
    pair.field.add(name='value', json_name='value', number=2, type=3, label=1)
    # All supported scalar wire types, nested values, packed arrays, maps and oneof.
    types = [1, 2, 3, 4, 5, 6, 7, 8, 9, 12, 13, 14, 15, 16, 17, 18]
    for i, kind in enumerate(types, 1):
        field = msg.field.add(name=f'f{i}', json_name=f'f{i}', number=i, type=kind, label=1)
        if kind == 14: field.type_name = '.telemetry.Sample.State'
    msg.field.add(name='child', json_name='child', number=17, type=11, label=1, type_name='.telemetry.Sample.Child')
    msg.field.add(name='values', json_name='values', number=18, type=18, label=3)
    msg.field.add(name='labels', json_name='labels', number=19, type=11, label=3, type_name='.telemetry.Sample.LabelsEntry')
    msg.oneof_decl.add(name='choice')
    msg.field.add(name='text', json_name='text', number=20, type=9, label=1, oneof_index=0)
    msg.field.add(name='code', json_name='code', number=21, type=5, label=1, oneof_index=0)
    pool = descriptor_pool.DescriptorPool(); pool.Add(file)
    cls = message_factory.GetMessageClass(pool.FindMessageTypeByName('telemetry.Sample'))
    sample = cls(f1=1.25, f2=-2.5, f3=-9223372036854775808, f4=18446744073709551615,
                 f5=-2147483648, f6=9007199254740993, f7=4294967295, f8=True, f9='月球',
                 f10=b'\x00\xff\x01', f11=4294967295, f12=1, f13=-2147483648,
                 f14=-9223372036854775808, f15=-2147483648, f16=-9223372036854775808,
                 child={'a': 7, 'b': 'nested'}, values=[-1, 0, 9223372036854775807],
                 labels={'x': 9007199254740993, 'y': -9}, code=8)
    return pb.FileDescriptorSet(file=[file]).SerializeToString(), cls, sample


def main():
    work = ROOT / '_interop/protobuf'; work.mkdir(parents=True, exist_ok=True)
    descriptor, cls, sample = schema()
    payload = sample.SerializeToString(deterministic=True)
    (work/'schema.bin').write_bytes(descriptor); (work/'payload.bin').write_bytes(payload)
    expected = json_format.MessageToDict(sample)
    if '--generate' in sys.argv:
        def hx(b): return '@moonmcap.decode_hex("'+b.hex()+'")'
        code = '''// Generated by tools/protobuf_workflows.py --generate using protobuf 6.33.0.
///|
fn protobuf_fixture() -> Bytes raise @moonmcap.McapError { DESC }

///|
test "descriptor scalar matrix matches official protobuf runtime" {
  let decoder = @moonmcap.protobuf_decoder(protobuf_fixture(), options={ ..@moonmcap.protobuf_options(), int64_as_string: true })
  let result = decoder.decode("telemetry.Sample", PAYLOAD)
  assert_eq(result, @json.parse(EXPECTED))
}
'''.replace('DESC',hx(descriptor)).replace('PAYLOAD',hx(payload)).replace('EXPECTED', json.dumps(json.dumps(expected, ensure_ascii=True), ensure_ascii=True))
        (ROOT/'protobuf_fixture_test.mbt').write_text(code, encoding='utf-8')
        print('Generated portable descriptor/scalar oracle fixture'); return
    subprocess.run([os.environ.get('MOON','moon'),'build','--target','js'], cwd=ROOT, check=True, capture_output=True)
    cli = ROOT/'_build/js/debug/build/cmd/decode/decode.js'
    def run(*args):
        return subprocess.run([os.environ.get('NODE','node'),str(cli),*map(str,args)], cwd=ROOT,capture_output=True,text=True,encoding='utf-8',timeout=90)
    def raw(data, strings=False):
        (work/'payload.bin').write_bytes(data)
        result=run('raw',work/'schema.bin',work/'payload.bin','telemetry.Sample',*(['--int64-strings'] if strings else []))
        assert result.returncode==0,result.stderr
        return json.loads(result.stdout)
    assert raw(payload,True)==expected
    numeric=raw(payload)
    assert numeric['f4']==18446744073709551615 and numeric['f3']==-9223372036854775808
    # Singular nested fragments merge, oneof last member wins, unknown groups skip.
    variants=[payload, b'\x8a\x01\x02\x08\x09\x8a\x01\x03\x12\x01x',
              b'\xa2\x01\x01a\xa8\x01\x07', b'\x9b\x06\x08\x01\x9c\x06'+payload,
              b'\x90\x01\x01\x92\x01\x02\x00\x02', b'\x9a\x01\x00',
              b'\x61\x00\x00\x00\x00\x00\x00\x00\x00' if False else b'\x60\x7f']
    for data in variants:
        decoded=cls();decoded.ParseFromString(data)
        wanted=json_format.MessageToDict(decoded)
        # Absent map fields are explicitly defaulted in entries by the decoder.
        assert raw(data,True)==wanted,(raw(data,True),wanted)
    for bad in [b'\x80'*11,b'\x00',b'\x4a\x01\xff',b'\x09\x00',b'\x4c',b'\x9b\x06']:
        (work/'payload.bin').write_bytes(bad)
        result=run('raw',work/'schema.bin',work/'payload.bin','telemetry.Sample')
        assert result.returncode==2,(bad,result.stdout,result.stderr)
    sources=[];digests=[]
    for mode in CompressionType:
        data=io.BytesIO();writer=Writer(data,compression=mode,chunk_size=128,enable_data_crcs=True);writer.start(profile='protobuf')
        sid=writer.register_schema('telemetry.Sample','protobuf',descriptor)
        cid=writer.register_channel('/telemetry','protobuf',sid)
        for i in range(12):
            message=cls(f4=9007199254740993+i, code=i)
            writer.add_message(cid,i,message.SerializeToString(),i,i)
        writer.finish();path=work/f'{mode.name}.mcap';path.write_bytes(data.getvalue());sources.append(path);digests.append(hashlib.sha256(data.getvalue()).hexdigest())
    where=json.dumps({'path':'/f4','op':'>=','value':9007199254740998})
    result=run(*sources,'--where',where,'--select','/f4','--offset',2,'--limit',5)
    assert result.returncode==0,result.stderr
    rows=[json.loads(s) for s in result.stdout.splitlines()]
    assert len(rows)==5 and [r['decoded']['data']['/f4'] for r in rows]==[9007199254740998,9007199254740999,9007199254740999,9007199254740999,9007199254741000],rows
    for path,digest in zip(sources,digests):assert hashlib.sha256(path.read_bytes()).hexdigest()==digest
    bad=work/'bad.mcap';data=io.BytesIO();writer=Writer(data);writer.start();sid=writer.register_schema('telemetry.Sample','protobuf',descriptor);cid=writer.register_channel('/bad','protobuf',sid);writer.add_message(cid,0,b'\x80'*11,0);writer.finish();bad.write_bytes(data.getvalue())
    output=work/'failed.ndjson';output.unlink(missing_ok=True)
    result=run(bad,'--output',output);assert result.returncode==2 and not output.exists()
    report={'result':'passed','reference':'Google protobuf 6.33.0','wire_variants':len(variants),'malformed_cases':6,'compressions':3,'integer_precision':'UInt64 full range retained; exact filter before global pagination','atomic_failures':1}
    (work/'report.json').write_text(json.dumps(report,indent=2)+'\n')
    print('Protobuf workflows passed: official wire oracle, 3 codecs, exact numeric predicates, atomic failure')


if __name__=='__main__':main()
