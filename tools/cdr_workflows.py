def plain(value):
    if dataclasses.is_dataclass(value):return {field.name:plain(getattr(value,field.name)) for field in dataclasses.fields(value) if field.name!='structure_needs_at_least_one_member' and not field.name.startswith('__')}
    if isinstance(value,np.ndarray):return [plain(v) for v in value]
    if isinstance(value,(list,tuple)):return [plain(v) for v in value]
    if isinstance(value,np.generic):value=value.item()
    if isinstance(value,float) and not math.isfinite(value):return 'NaN' if math.isnan(value) else ('Infinity' if value>0 else '-Infinity')
    return value


